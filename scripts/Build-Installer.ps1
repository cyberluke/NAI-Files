# Builds the NAI Files setup executable: a WinForms bootstrapper that embeds
# the NAI CA certificates, downloads the signed MSIX, verifies it against the
# SHA-256 compiled into the EXE, provisions the CA trust with one UAC prompt and
# installs the package for the current user.

[CmdletBinding()]
param(
	[string]$MsixPath = "",
	[string]$Version = "",
	[string]$OutDir = "",
	[string]$CertDir = "D:\_SATIN_AI\_NAI_CA_AUTHORITY\certs",
	[string]$LeafThumbprint = "1FA3E6A536352A37342742CEBED4CA546944F5F7",
	[string]$ExpectedSubject = "CN=NAI OS, O=NANOTRIK.AI",
	[string]$IdentityName = "NAI.Files",
	[string]$ApplicationId = "App",
	[string]$PublicBaseUrl = "https://updates.nanotrik.ai/NAI-Files/",
	[string]$Signtool = "C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\signtool.exe",
	[switch]$SkipSign
)

$ErrorActionPreference = "Stop"

$repo = Split-Path -Parent $PSScriptRoot
if ([string]::IsNullOrWhiteSpace($MsixPath))
{
	throw "Pass -MsixPath pointing at the signed .msix to wrap."
}
$MsixPath = (Resolve-Path -LiteralPath $MsixPath).Path
if ([string]::IsNullOrWhiteSpace($Version))
{
	$folder = Split-Path -Leaf (Split-Path -Parent $MsixPath)
	if ($folder -match '^(\d+\.\d+\.\d+\.\d+)$') { $Version = $Matches[1] }
	if ([string]::IsNullOrWhiteSpace($Version)) { throw "Pass -Version; it could not be derived from the package path." }
}
if ([string]::IsNullOrWhiteSpace($OutDir)) { $OutDir = Join-Path $repo "artifacts\installer" }
New-Item -ItemType Directory -Path $OutDir -Force | Out-Null

# The package must already be signed by the expected leaf; wrapping an unsigned
# or wrongly signed package would produce an installer that cannot work.
# Get-AuthenticodeSignature cannot read the AppX signature block, so use signtool.
$verify = & $Signtool verify /pa /all /v $MsixPath 2>&1
if ($LASTEXITCODE -ne 0) { throw "Package signature verification failed. Sign the MSIX before wrapping it." }
$expectedCn = ($ExpectedSubject -replace '^CN=([^,]+).*$', '$1')
if (-not ($verify -match [regex]::Escape("Issued to: $expectedCn"))) {
	throw "Package is not signed by '$ExpectedSubject'."
}

$sha256 = (Get-FileHash -LiteralPath $MsixPath -Algorithm SHA256).Hash

$buildDir = Join-Path $repo "packaging\installer\build"
New-Item -ItemType Directory -Path $buildDir -Force | Out-Null
@'
*
!.gitignore
'@ | Set-Content -LiteralPath (Join-Path $buildDir ".gitignore") -Encoding ascii

$configPath = Join-Path $buildDir "InstallerConfig.g.cs"
$baseUrl = ($PublicBaseUrl.TrimEnd('/') + "/" + $Version + "/")
$config = @"
// GENERATED by scripts/Build-Installer.ps1 — do not edit.
internal static class InstallerConfig
{
    public const string ProductName = "NAI Files";
    public const string IdentityName = "$IdentityName";
    public const string ApplicationId = "$ApplicationId";
    public const string MsixFileName = "NAI-Files.msix";
    public const string BaseUrl = "$baseUrl";
    public const string ExpectedSubject = "$ExpectedSubject";
    public const string ExpectedSha256 = "$($sha256.ToLowerInvariant())";
}
"@
Set-Content -LiteralPath $configPath -Value $config -Encoding UTF8

$csc = Join-Path $env:WINDIR "Microsoft.NET\Framework64\v4.0.30319\csc.exe"
if (-not (Test-Path -LiteralPath $csc)) { throw "C# compiler not found: $csc" }

$exe = Join-Path $OutDir "NAI-Files-Setup-$Version.exe"
$cscArgs = @(
	"/nologo",
	"/target:winexe",
	"/platform:anycpu",
	"/optimize+",
	"/out:$exe",
	"/reference:System.dll",
	"/reference:System.Drawing.dll",
	"/reference:System.Windows.Forms.dll",
	"/resource:$(Join-Path $CertDir 'NAI-Sovereign-Root-CA.cer'),NAI-Root.cer",
	"/resource:$(Join-Path $CertDir 'NAI-Code-Signing-CA.cer'),NAI-Inter.cer",
	"/resource:$(Join-Path $CertDir 'NAI-OS.cer'),NAI-Leaf.cer",
	(Join-Path $repo "packaging\installer\Installer.cs"),
	$configPath
)

Write-Host "Compiling $exe"
& $csc @cscArgs
if ($LASTEXITCODE -ne 0) { throw "csc failed with exit code $LASTEXITCODE" }

if (-not $SkipSign)
{
	Write-Host "Signing setup executable"
	& $Signtool sign /fd SHA256 /sha1 $LeafThumbprint /tr "http://timestamp.digicert.com" /td SHA256 $exe
	if ($LASTEXITCODE -ne 0) { throw "signtool sign failed with exit code $LASTEXITCODE" }
	& $Signtool verify /pa /all $exe
	if ($LASTEXITCODE -ne 0) { throw "signtool verify failed with exit code $LASTEXITCODE" }
}

$info = Get-Item -LiteralPath $exe
Write-Output ""
Write-Output "Setup:    $($info.FullName)"
Write-Output "Size:     $($info.Length) bytes"
Write-Output "Version:  $Version"
Write-Output "Package:  $baseUrl$('NAI-Files.msix')"
Write-Output "SHA-256:  $sha256"
